local log, tag = HS3.log, HS3.tagName
local KSL = StaticFindObject("/Script/Engine.Default__KismetSystemLibrary")
local r = {}
KSL:GetPrimaryAssetIdList({ Name = FName("AnimalFieldJournalEntryDataAsset") }, r)
local o = KSL:LoadAsset_Blocking(KSL:GetSoftObjectReferenceFromPrimaryAssetId(r[1]:get()))
log("animal " .. o:GetFName():ToString())
local function t(nome, f) local ok, v = pcall(f); log("  " .. nome .. " -> " .. (ok and tostring(v) or ("ERRO " .. tostring(v)))) end
t("EntryTitle", function() return o.EntryTitle:ToString() end)
t("AnimalTag", function() return tag(o.AnimalTag) end)
t("HeaderTag", function() return tag(o.FieldJournalHeaderTag) end)
t("InfoText", function() return o.InfoFrameData1.InfoText:ToString() end)
t("ScheduleInfo", function() return tostring(o.ScheduleInfo) end)
t("ScheduleInfo.TitleText", function() return o.ScheduleInfo.TitleText:ToString() end)
t("ScheduleInfo.InfoSections", function() local n = 0; o.ScheduleInfo.InfoSections:ForEach(function(_, e) n = n + 1; log("    sec: " .. e:get().SectionText:ToString()) end); return n end)
t("HabitatInfo.TitleText", function() return o.HabitatInfo.TitleText:ToString() end)
t("HabitatInfo.InfoSections", function() local n = 0; o.HabitatInfo.InfoSections:ForEach(function(_, e) n = n + 1 end); return n end)
t("ThrophyInfo.TitleText", function() return o.ThrophyInfo.TitleText:ToString() end)
t("IncludedMaps", function() local n = 0; o.IncludedMaps:ForEach(function(_, e) n = n + 1; log("    mapa: " .. e:get().PrimaryAssetName:ToString()) end); return n end)
t("IncludedMaps2", function() local n = 0; o.IncludedMaps:ForEach(function(_, e) n = n + 1; log("    mapa: " .. tostring(e:get():ToString())) end); return n end)
log("animal_campos fim")
